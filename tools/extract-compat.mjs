// Sandbox · Team 15 compat extraction
//
// Two submissions keep the code the dashboard needs inside their demo.html
// instead of module.js. Rather than retyping anything, this tool copies those
// exact bytes out of the (untouched) team folders into shell/compat/:
//
//   Team 1  first inline <script> of demo.html -> shell/compat/team01_fcfs_sjf.inline.js (byte-identical)
//   Team 4  the <div class="os-team04"> markup -> shell/compat/team04_round_robin.markup.js (as a JS string)
//
//   node tools/extract-compat.mjs
//
// tools/verify.mjs re-derives both extractions and fails if they drift.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const compatDir = path.join(root, "shell", "compat");

export function extractTeam01(root) {
  const file = path.join(root, "modules", "team01_fcfs_sjf", "demo.html");
  const bytes = fs.readFileSync(file);
  const open = Buffer.from("<script>");
  const close = Buffer.from("</script>");
  const start = bytes.indexOf(open);
  if (start < 0) throw new Error("Team 1: no inline <script> found in demo.html");
  const from = start + open.length;
  const to = bytes.indexOf(close, from);
  if (to < 0) throw new Error("Team 1: inline <script> is not closed");
  return { bytes: bytes.subarray(from, to), from, to, file };
}

export function extractTeam04(root) {
  const file = path.join(root, "modules", "team04_round_robin", "demo.html");
  const bytes = fs.readFileSync(file);
  const open = Buffer.from('<div class="os-team04">');
  const script = Buffer.from('<script src="module.js"></script>');
  const start = bytes.indexOf(open);
  const scriptAt = bytes.indexOf(script);
  if (start < 0 || scriptAt < 0) throw new Error("Team 4: markup anchors not found in demo.html");
  const end = bytes.lastIndexOf(Buffer.from("</div>"), scriptAt) + "</div>".length;
  if (end <= start) throw new Error("Team 4: closing </div> not found");
  return { markup: bytes.subarray(start, end).toString("utf8"), from: start, to: end, file };
}

// JSON string with every non-ASCII character escaped, so the file decodes the same under any charset.
export function asciiString(text) {
  return JSON.stringify(text).replace(/[\u007f-￿]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
}

function run() {
  fs.mkdirSync(compatDir, { recursive: true });

  const t1 = extractTeam01(root);
  fs.writeFileSync(path.join(compatDir, "team01_fcfs_sjf.inline.js"), t1.bytes);
  console.log(`team01: ${t1.bytes.length} bytes from demo.html [${t1.from}, ${t1.to})`);

  const t4 = extractTeam04(root);
  const js =
    `/* Generated by tools/extract-compat.mjs from modules/team04_round_robin/demo.html, bytes [${t4.from}, ${t4.to}). Do not edit. */\n` +
    "window.Sandbox = window.Sandbox || {};\n" +
    "window.Sandbox.compat = window.Sandbox.compat || {};\n" +
    `window.Sandbox.compat.team04Markup = ${asciiString(t4.markup)};\n`;
  fs.writeFileSync(path.join(compatDir, "team04_round_robin.markup.js"), js);
  console.log(`team04: ${t4.markup.length} characters of markup from demo.html [${t4.from}, ${t4.to})`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) run();
